-- schema v8 —— 作業是「怎麼結束的」，不只是「結束在哪個狀態」
--
-- 欄位與值域的權威是 docs/architecture/data-model.md。**改這裡就要改那一份。**

-- ── 為什麼「已取消」不夠 ────────────────────────────────────
--
-- 關掉程式的時候，正在跑的作業會被取消 —— 那是對的，語意跟使用者自己按取消
-- 完全一樣（ADR-0023：取消不回滾，已寫入的保留）。
--
-- 但還有第二種情形：**程式沒有機會取消就死了**（工作管理員、當掉、斷電）。
-- 那些列會留在 `running`，而在 2026-09-10 之前它們會永遠留在那裡：
--
--   · 作業紀錄那顆徽章永遠寫「執行中」，而且沒有取消鍵
--     （按鈕綁的是記憶體裡的 `live`，重開之後那是 false）
--   · `hasRunningRun()` 讓**之後每一次搜尋**都掛一句「有作業還在跑」
--
-- 現在啟動之後第一次開這個專題時會把它們掃掉。掃掉之後它們也是 `cancelled` ——
-- 於是畫面上「你按了結束」與「上次沒有正常關閉」長得一模一樣。
--
-- **這一欄就是把那兩件事分開。** 不新增第七個狀態：
-- 多一個狀態值會讓每一個讀 `status` 的地方都要多處理一種情形，
-- 而分辨它們只需要一個旁邊的欄位。
--
--   NULL       —— 使用者自己按的取消，或這一列根本不是取消
--   'shutdown' —— 關閉程式時一起取消的
--   'stale'    —— 掃描標的：上一次結束時它還沒跑完（分不出是關閉時沒趕上收尾，
--                 還是被強制結束的 —— 所以那句話不可以說「沒有正常關閉」）
--
-- （webscouts 對同一件事的處方是新增一個 `interrupted` 狀態，
--   因為**它的作業可以續跑**，游標留著；cyclosa 沒有續跑，
--   所以那個區別在這裡買不到東西。借的是理由，不是形狀。）
ALTER TABLE run ADD COLUMN ended_reason TEXT
  CHECK (ended_reason IS NULL OR ended_reason IN ('shutdown', 'stale'));
